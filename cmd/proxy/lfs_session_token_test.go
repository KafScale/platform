package main

import (
	"context"
	"io"
	"log/slog"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"

	"github.com/aws/aws-sdk-go-v2/service/s3"
)

// These are the two credential channels generated by lfsProxyCredentialEnv.
// Verify the SDK signs with the token belonging to the selected key pair.
func TestInitLFSModuleSignsWithMatchingSessionToken(t *testing.T) {
	for _, tc := range []struct {
		name, staticKey, staticToken, fallbackKey, fallbackToken, wantKey, wantToken string
	}{
		{name: "AWS temporary pair", staticKey: "aws-key", staticToken: "aws-token", wantKey: "aws-key", wantToken: "aws-token"},
		{name: "KafScale temporary pair", fallbackKey: "ks-key", fallbackToken: "ks-token", wantKey: "ks-key", wantToken: "ks-token"},
		{name: "both temporary pairs prefer AWS", staticKey: "aws-key", staticToken: "aws-token", fallbackKey: "ks-key", fallbackToken: "ks-token", wantKey: "aws-key", wantToken: "aws-token"},
		{name: "permanent AWS pair ignores KafScale token", staticKey: "aws-key", fallbackKey: "ks-key", fallbackToken: "ks-token", wantKey: "aws-key"},
		{name: "KafScale pair ignores unmatched AWS token", staticToken: "unmatched-aws-token", fallbackKey: "ks-key", fallbackToken: "ks-token", wantKey: "ks-key", wantToken: "ks-token"},
		{name: "whitespace AWS pair uses padded KafScale pair", staticKey: "  ", staticToken: " ", fallbackKey: " ks-key\n", fallbackToken: "\tks-token ", wantKey: "ks-key", wantToken: "ks-token"},
		{name: "whitespace KafScale session token is no token", fallbackKey: "ks-key", fallbackToken: "  ", wantKey: "ks-key"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			requests := make(chan http.Header, 1)
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				select {
				case requests <- r.Header.Clone():
				default:
				}
				w.WriteHeader(http.StatusOK)
			}))
			defer server.Close()
			t.Setenv("KAFSCALE_LFS_PROXY_S3_BUCKET", "test-session-bucket")
			t.Setenv("KAFSCALE_LFS_PROXY_S3_REGION", "us-east-1")
			t.Setenv("KAFSCALE_LFS_PROXY_S3_ENDPOINT", server.URL)
			t.Setenv("KAFSCALE_LFS_PROXY_S3_ACCESS_KEY", tc.staticKey)
			staticSecret := ""
			if tc.staticKey != "" {
				staticSecret = "aws-secret"
			}
			t.Setenv("KAFSCALE_LFS_PROXY_S3_SECRET_KEY", staticSecret)
			t.Setenv("KAFSCALE_LFS_PROXY_S3_SESSION_TOKEN", tc.staticToken)
			t.Setenv("AWS_ACCESS_KEY_ID", tc.fallbackKey)
			fallbackSecret := ""
			if tc.fallbackKey != "" {
				fallbackSecret = "ks-secret"
			}
			t.Setenv("AWS_SECRET_ACCESS_KEY", fallbackSecret)
			t.Setenv("AWS_SESSION_TOKEN", tc.fallbackToken)
			t.Setenv("KAFSCALE_LFS_PROXY_S3_ENSURE_BUCKET", "false")
			t.Setenv("KAFSCALE_LFS_TRACKER_ENABLED", "false")
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			module, err := initLFSModule(ctx, slog.New(slog.NewTextHandler(io.Discard, nil)))
			if err != nil {
				t.Fatal(err)
			}
			if _, err := module.s3Uploader.api.HeadBucket(ctx, &s3.HeadBucketInput{Bucket: &module.s3Bucket}); err != nil {
				t.Fatal(err)
			}
			headers := <-requests
			if got := headers.Get("X-Amz-Security-Token"); got != tc.wantToken {
				t.Fatalf("signed request token = %q, want %q", got, tc.wantToken)
			}
			if auth := headers.Get("Authorization"); !strings.Contains(auth, "Credential="+tc.wantKey+"/") {
				t.Fatalf("request did not use expected key %q", tc.wantKey)
			}
		})
	}
}
